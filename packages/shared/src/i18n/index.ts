export const dictionaries: Record<Locale, Dictionary> = {
  'zh-CN': zhCN,
  'en-US': enUS,
};

const pluralRulesByLocale = new Map<Locale, Intl.PluralRules>();

function pluralRulesFor(locale: Locale): Intl.PluralRules {
  const cached = pluralRulesByLocale.get(locale);
  if (cached) return cached;
  const rules = new Intl.PluralRules(locale);
  pluralRulesByLocale.set(locale, rules);
  return rules;
}

/** Pick `key_<category>` from Intl.PluralRules when `{count}` is a number. */
function pluralMessage(locale: Locale, key: string, count: number): string | undefined {
  const dictionary = dictionaries[locale];
  if (!dictionary) return undefined;
  const category = pluralRulesFor(locale).select(count);
  return dictionary[`${key}_${category}`] ?? dictionary[`${key}_other`];
}

/**
 * Interpolates `{name}` from `vars`. Plural keys are chosen only when `count` is a number.
 * A formatted string such as `"1,234"` stays on the base key.
 */
export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const count = vars?.count;
  const plural = typeof count === 'number' ? pluralMessage(locale, key, count) : undefined;
  const raw = plural ?? dictionaries[locale]?.[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}

/** Localized copy for `error.data.appCode`. Unknown codes use the generic sentence. */
export function appErrorMessage(locale: Locale, appCode: unknown): string {
  if (isAppErrorCode(appCode)) {
    const key = `error.app.${appCode}`;
    const text = t(locale, key);
    if (text !== key) return text;
  }
  return t(locale, 'error.app.unknown');
}

const FIELD_ERROR_CODE = /^[a-z][a-z0-9]*(_[a-z0-9]+)*$/;

export function fieldErrorCodes(locale: Locale): string[] {
  return Object.keys(dictionaries[locale] ?? {})
    .filter((key) => key.startsWith('error.field.'))
    .map((key) => key.slice('error.field.'.length))
    .sort();
}

/**
 * Localized copy for a zod issue message that is a snake_case field code.
 * Anything else, including an unmapped code, uses `error.app.UNKNOWN`.
 */
export function fieldErrorMessage(locale: Locale, code: unknown): string {
  const unknown = t(locale, 'error.app.UNKNOWN');
  if (typeof code !== 'string' || !FIELD_ERROR_CODE.test(code)) return unknown;
  const text = dictionaries[locale]?.[`error.field.${code}`];
  return text ?? unknown;
}
